CREATE TABLE IF NOT EXISTS evaluation_cycles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year INTEGER NOT NULL,
    quarter INTEGER NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    invitation_date DATE NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_evaluation_cycles_year_quarter UNIQUE (year, quarter),
    CONSTRAINT ck_evaluation_cycles_quarter CHECK (quarter BETWEEN 1 AND 4)
);

CREATE INDEX IF NOT EXISTS ix_evaluation_cycles_year
    ON evaluation_cycles (year);